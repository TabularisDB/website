// Plugin developer / manifest reference — generated live by the registry
// (core schema + configured kinds + examples), re-published as a wiki page so
// tabularis.dev stays the single docs entry point. The registry ships its own
// title/excerpt frontmatter; we add the wiki's order/category, absolutize
// root-relative registry links that would otherwise resolve against
// tabularis.dev, and reword the passages where the registry talks about
// itself ("this instance", "the buttons at the top of this page"), which read
// out of context here.

// Exact-match rewrites: when the registry rewords one of these, the build
// warns and keeps the upstream text — update the pair below.
function rewrites(registryUrl, host) {
    return [
        ['publish them to this Tabularium registry', 'publish them to the registry'],
        [
            '**Tabularium** is the registry it pulls plugins from — this instance, or ',
            'The **registry** is where it pulls plugins from — ',
        ],
        ['or any other self-hosted Tabularium your users', 'or any self-hosted registry your users'],
        ['packaged and submitted here so', 'packaged and submitted to the registry so'],
        ['list every manifest field this registry expects', 'list every manifest field the registry expects'],
        [' (also linked in the page header)', ''],
        ['which fields and constraints this registry expects', 'which fields and constraints the registry expects'],
        ['## Publishing to this registry', '## Publishing to the registry'],
        [
            'CI can validate against this registry via `POST /api/manifest/validate`',
            `CI can validate against the registry via \`POST ${registryUrl}/api/manifest/validate\``,
        ],
        [
            'The admin may require manual approval — check `/requests` after submitting.',
            `The registry admin may require manual approval — check \`${host}/requests\` after submitting.`,
        ],
        ['## Using this registry from Tabularis', '## Using the registry from Tabularis'],
        ['point their Tabularis at any Tabularium by setting', 'point their Tabularis at any registry by setting'],
        ['**Tabularium source (this registry)**', '**Registry source**'],
        [
            'the **Raw markdown ↗** and **Copy as markdown** buttons at the top of this page surface everything as one flat document at',
            'this page is also available as one flat Markdown document at',
        ],
        ['review plugin manifests against this registry', 'review plugin manifests against the registry'],
        ['Open an issue against [Tabularium](', 'Open an issue against the [registry]('],
        [", or ping this instance's admin.", '.'],
        ['_Generated by Tabularium for ', '_Generated by the registry at '],
    ];
}

export function toWikiPage(raw, registryUrl) {
    const host = new URL(registryUrl).host;
    let md = raw.replaceAll('](/', `](${registryUrl}/`);

    // [`/submit`](https://registry…/submit) — the path alone would read as a tabularis.dev URL.
    md = md.replace(/\[`(\/[^`]*)`\]\(([^)]+)\)/g, (link, path, href) =>
        href.startsWith(registryUrl) ? `[\`${host}${path}\`](${href})` : link,
    );

    for (const [from, to] of rewrites(registryUrl, host)) {
        if (md.includes(from)) {
            md = md.replaceAll(from, to);
        } else {
            console.warn(`plugin dev docs: rewrite no longer matches upstream, update scripts/plugin-dev-docs.mjs: ${from}`);
        }
    }

    const leftovers = md.match(/.*(\bTabularium\b|this registry|this instance).*/g);
    if (leftovers) {
        console.warn(`plugin dev docs: registry-specific wording left after rewrites:\n${leftovers.join('\n')}`);
    }

    return md.replace(/^---\n/, `---\norder: 8.6\ncategory: "Integration"\n`);
}
